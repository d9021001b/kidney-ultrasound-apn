ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / "CYCH_attention_weighted_directional_development_20260914"
OUT = ROOT / "CYCH_crossfit_attention_directional_development_20260914"
INNER_FOLDS = 4


def read_csv(path: Path) -> pd.DataFrame:
    return pd.read_csv(path, dtype={"patient_id": str})


def require_lock() -> None:
    lock = json.loads((OUT / "protocol_locked.json").read_text(encoding="utf-8"))
    assert lock["protocol_sha256"] == sha256(OUT / "protocol.json")
    assert lock["source_sha256"] == sha256(Path(__file__))


def prepare() -> None:
    for name in ("models", "features", "source"):
        (OUT / name).mkdir(parents=True, exist_ok=True)
    for name in ("image_manifest.csv", "patients.csv", "random_patient_assignments.csv"):
        source = SOURCE / name
        destination = OUT / name
        if destination.exists():
            assert sha256(destination) == sha256(source)
        else:
            shutil.copy2(source, destination)
    decision = json.loads((SOURCE / "development_decision.json").read_text(encoding="utf-8"))
    assert decision["selected"] == "PAIR+ATTN-I3"
    patients = read_csv(OUT / "patients.csv")
    assignments = read_csv(OUT / "random_patient_assignments.csv")
    assert len(patients) == 98 and int(patients.label.sum()) == 52
    for seed in R.SEEDS:
        indices_for(patients, assignments, seed)
    protocol = {
        "scope": "development-only cross-fitted attention correction; the already viewed exploratory test is not accessed",
        "rationale": "The prior second-stage I3 head used in-sample attention features for training patients. Cross-fitting makes every outer-training patient's attention weights come from a model that did not train on that patient.",
        "outer_draws": {"seeds": R.SEEDS, "train": 58, "development": 20},
        "inner_crossfit": {"folds": INNER_FOLDS, "splitter": "StratifiedKFold(shuffle=True, random_state=outer seed)", "unit": "patient"},
        "attention": "Unchanged locked gated-attention architecture and optimization: train-only scaler/PCA(32), hidden 32, attention 16, 300 epochs",
        "features": {
            "dense_image_sha256": sha256(DENSE_IMAGE),
            "i3_image_sha256": sha256(I3_IMAGE),
        },
        "second_stage": "Fit the unchanged L2 logistic I3 head on 58 out-of-fold attention-weighted training features; predict development features generated by one attention model fitted to all 58 outer-training patients",
        "vote": "Unchanged equal-probability radiomics, DenseNet, and cross-fitted attention-weighted I3, implemented as (2*PAIR + I3)/3",
        "gate": "Relative to pair+unweighted-I3 reference, both mean development metrics improve and at least 6/10 draws improve jointly",
        "test_policy": "No exploratory-test metric may be computed because that role was already viewed for the preceding locked candidate. Confirmation requires source-clear new patients.",
        "source_decision_sha256": sha256(SOURCE / "development_decision.json"),
    }
    protocol_path = OUT / "protocol.json"
    if protocol_path.exists():
        assert json.loads(protocol_path.read_text(encoding="utf-8")) == protocol
    else:
        write_json(protocol_path, protocol)
    lock_path = OUT / "protocol_locked.json"
    if not lock_path.exists():
        write_json(lock_path, {"utc": datetime.now(timezone.utc).isoformat(), "protocol_sha256": sha256(protocol_path), "source_sha256": sha256(Path(__file__))})
    shutil.copy2(__file__, OUT / "source" / Path(__file__).name)
    print("Cross-fitted attention protocol locked", flush=True)


def load_reference(path: Path, group: str, aliases: list[str]) -> dict[int, np.ndarray]:
    frame = pd.read_csv(path)
    frame = frame.loc[frame.role.eq("development_validation") & frame.group.eq(group), ["seed", "patient_alias", "score"]]
    result = {}
    for seed in R.SEEDS:
        subset = frame.loc[frame.seed.eq(seed)].set_index("patient_alias")
        assert len(subset) == 20 and subset.index.is_unique
        result[seed] = subset.reindex(aliases).score.to_numpy(float)
    return result


def fit_attention(
    model_seed: int,
    fit_patients: np.ndarray,
    labels: np.ndarray,
    dense: np.ndarray,
    manifest: pd.DataFrame,
    patients: pd.DataFrame,
):
    fit_ids = set(patients.patient_id.iloc[fit_patients])
    fit_images = manifest.patient_id.isin(fit_ids).to_numpy()
    scaler = StandardScaler().fit(dense[fit_images])
    standardized = scaler.transform(dense)
    pca = PCA(n_components=32, random_state=model_seed).fit(standardized[fit_images])
    reduced = pca.transform(standardized).astype(np.float32)
    bags, masks, image_ids = build_bags(reduced, manifest, patients)
    model, scores, attention, losses = train_one(model_seed, fit_patients, labels, bags, masks)
    return model, scaler, pca, scores, attention, image_ids, losses


def evaluate() -> None:
    require_lock()
    import torch

    torch.set_num_threads(4)
    patients = read_csv(OUT / "patients.csv")
    manifest = read_csv(OUT / "image_manifest.csv")
    assignments = read_csv(OUT / "random_patient_assignments.csv")
    labels = patients.label.to_numpy(int)
    aliases = patients.patient_alias.tolist()
    dense = np.load(DENSE_IMAGE)
    i3_frame = pd.read_csv(I3_IMAGE)
    assert i3_frame.image_id.tolist() == manifest.image_id.tolist()
    i3_image = i3_frame.drop(columns="image_id").to_numpy(np.float32)
    pair_reference = load_reference(PAIR_PREDICTIONS, "PAIR", aliases)
    i3_reference = load_reference(I3_PREDICTIONS, "I3-ALL", aliases)

    metrics, predictions, attention_rows, provenance = [], [], [], []
    for outer_seed in R.SEEDS:
        indices = indices_for(patients, assignments, outer_seed)
        outer_train = indices["train"]
        development = indices["validation"]
        oof_features = np.full((98, 50), np.nan, dtype=np.float32)
        splitter = StratifiedKFold(n_splits=INNER_FOLDS, shuffle=True, random_state=outer_seed)
        fold_records = []
        for fold, (fit_local, holdout_local) in enumerate(splitter.split(outer_train, labels[outer_train])):
            fit_patients = outer_train[fit_local]
            holdout_patients = outer_train[holdout_local]
            model_seed = outer_seed + 1000 * (fold + 1)
            model, scaler, pca, _, attention, _, losses = fit_attention(
                model_seed, fit_patients, labels, dense, manifest, patients
            )
            weighted = weighted_directional_features(i3_image, attention, manifest, patients)
            oof_features[holdout_patients] = weighted[holdout_patients]
            model_path = OUT / "models" / f"attention_{outer_seed}_fold{fold}.pt"
            prep_path = OUT / "models" / f"preprocessing_{outer_seed}_fold{fold}.joblib"
            torch.save(model.state_dict(), model_path)
            joblib.dump({"scaler": scaler, "pca": pca}, prep_path, compress=3)
            fold_records.append({"fold": fold, "fit_patients": len(fit_patients), "holdout_patients": len(holdout_patients), "model_sha256": sha256(model_path), "preprocessing_sha256": sha256(prep_path), **losses})
        assert np.isfinite(oof_features[outer_train]).all()

        full_model, full_scaler, full_pca, _, full_attention, image_ids, full_losses = fit_attention(
            outer_seed, outer_train, labels, dense, manifest, patients
        )
        full_weighted = weighted_directional_features(i3_image, full_attention, manifest, patients)
        head = make_head(outer_seed)
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            head.fit(oof_features[outer_train], labels[outer_train])
        directional_score = head.predict_proba(full_weighted)[:, 1]
        candidate = (2.0 * pair_reference[outer_seed] + directional_score) / 3.0
        incumbent = (2.0 * pair_reference[outer_seed] + i3_reference[outer_seed]) / 3.0
        metrics.append(metric_row(outer_seed, "PAIR+I3-REFERENCE", labels[development], incumbent[development]))
        metrics.append(metric_row(outer_seed, "PAIR+CROSSFIT-ATTN-I3", labels[development], candidate[development]))
        for index in development:
            predictions.append({"seed": outer_seed, "group": "PAIR+CROSSFIT-ATTN-I3", "role": "development_validation", "patient_alias": aliases[index], "label": int(labels[index]), "score": float(candidate[index])})
            for position, image_id in enumerate(image_ids[index]):
                attention_rows.append({"seed": outer_seed, "role": "development_validation", "patient_alias": aliases[index], "image_id": image_id, "attention_weight": float(full_attention[index, position])})
        full_model_path = OUT / "models" / f"attention_{outer_seed}_full.pt"
        full_prep_path = OUT / "models" / f"preprocessing_{outer_seed}_full.joblib"
        head_path = OUT / "models" / f"crossfit_i3_{outer_seed}.joblib"
        torch.save(full_model.state_dict(), full_model_path)
        joblib.dump({"scaler": full_scaler, "pca": full_pca}, full_prep_path, compress=3)
        joblib.dump(head, head_path, compress=3)
        np.save(OUT / "features" / f"oof_attention_i3_{outer_seed}.npy", oof_features[outer_train])
        provenance.append({"seed": outer_seed, "inner_folds": fold_records, "full_model_sha256": sha256(full_model_path), "full_preprocessing_sha256": sha256(full_prep_path), "i3_head_sha256": sha256(head_path), "full_first_loss": full_losses["first_loss"], "full_last_loss": full_losses["last_loss"]})
        print(f"Cross-fitted attention complete: {outer_seed}", flush=True)

    frame = pd.DataFrame(metrics)
    reference = frame.loc[frame.group.eq("PAIR+I3-REFERENCE")].set_index("seed")
    candidate = frame.loc[frame.group.eq("PAIR+CROSSFIT-ATTN-I3")].set_index("seed")
    delta_auc = candidate.auroc - reference.auroc
    delta_ap = candidate.average_precision - reference.average_precision
    wins = int(((delta_auc > 0) & (delta_ap > 0)).sum())
    decision = {"selection_role": "development_validation", "delta_auroc": float(delta_auc.mean()), "delta_ap": float(delta_ap.mean()), "joint_wins": wins, "passed": bool(delta_auc.mean() > 0 and delta_ap.mean() > 0 and wins >= 6), "test_access": "prohibited; preceding exploratory test already viewed"}
    summary = frame.groupby("group", as_index=False).agg(mean_auroc=("auroc", "mean"), std_auroc=("auroc", "std"), mean_average_precision=("average_precision", "mean"), std_average_precision=("average_precision", "std"))
    summary["joint_target_draws"] = [int(((frame.loc[frame.group.eq(group), "auroc"] > 0.8) & (frame.loc[frame.group.eq(group), "average_precision"] > 0.8)).sum()) for group in summary.group]
    frame.to_csv(OUT / "development_metrics_per_draw.csv", index=False)
    summary.to_csv(OUT / "development_summary.csv", index=False)
    pd.DataFrame(predictions).to_csv(OUT / "development_predictions.csv", index=False)
    pd.DataFrame(attention_rows).to_csv(OUT / "development_image_attention.csv", index=False)
    write_json(OUT / "training_provenance.json", provenance)
    write_json(OUT / "development_decision.json", decision)
    lines = ["# Cross-fitted attention-weighted I3 development screen", "", "Every outer-training patient's attention features were generated out of fold. The previously viewed exploratory test was not accessed.", "", "| Group | Mean AUROC | Mean AP | Both >0.8 draws |", "|---|---:|---:|---:|"]
    for row in summary.itertuples():
        lines.append(f"| {row.group} | {row.mean_auroc:.3f} | {row.mean_average_precision:.3f} | {row.joint_target_draws}/10 |")
    lines.extend(["", "## Decision", "", f"Decision record: `{json.dumps(decision, separators=(',', ':'))}`"])
    (OUT / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(summary.to_string(index=False), flush=True)
    print(json.dumps(decision), flush=True)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("stage", choices=("prepare", "evaluate", "all"))
    args = parser.parse_args()
    stages = ("prepare", "evaluate") if args.stage == "all" else (args.stage,)
    for stage in stages:
        globals()[stage]()


if __name__ == "__main__":
    main()

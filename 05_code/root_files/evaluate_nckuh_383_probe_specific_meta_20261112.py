"""Shared frozen base representations, separately fitted convex/linear heads."""

import json
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import StratifiedKFold
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

from evaluate_nckuh_383_acquisition_strata_20261112 import bootstrap, metric, threshold_for_sensitivity
from prepare_nckuh_383_contour_cohort_20261111 import digest


ROOT = Path(__file__).resolve().parents[2]
EXP = ROOT / "02_experiments"
ROUTER = EXP / "NCKUH_revised_383_probe_router_20261112"
BASE = EXP / "NCKUH_revised_383_oof_hierarchy_stack_base_export_20261112"
REGISTRY = EXP / "NCKUH_revised_383_audit_20261111"
OUT = ROUTER / "shared_base_probe_heads"
SEED = 20261112
FEATURE_SETS = {
    "image_only": ["base_dino", "base_domain_residual_dino", "base_geometry"],
    "image_plus_demographics": ["base_dino", "base_domain_residual_dino", "base_geometry", "base_demographics"],
    "image_plus_clinical_hierarchy": ["base_dino", "base_domain_residual_dino", "base_geometry", "base_clinical_four_state"],
    "all_five": ["base_dino", "base_domain_residual_dino", "base_geometry", "base_demographics", "base_clinical_four_state"],
}


def head():
    return make_pipeline(SimpleImputer(strategy="median", keep_empty_features=True),
                         StandardScaler(), LogisticRegression(
                             C=.1, class_weight="balanced", solver="liblinear",
                             max_iter=3000, random_state=SEED))


def main():
    route = pd.read_csv(ROUTER / "image_routes.csv")
    image = pd.read_csv(REGISTRY / "contour_image_manifest.csv")
    people = pd.read_csv(REGISTRY / "patient_assignments.csv")
    routed = image[["image_id", "kidney_alias"]].merge(
        route[["image_id", "route"]], on="image_id", validate="one_to_one"
    )
    train = pd.read_csv(BASE / "training_oof_predictions.csv")
    dev = pd.read_csv(BASE / "development_predictions.csv")
    assert set(train.patient_alias).isdisjoint(dev.patient_alias)
    assert set(train.patient_alias) <= set(people.loc[people.role.eq("train"), "patient_alias"])
    assert set(dev.patient_alias) <= set(people.loc[people.role.eq("development"), "patient_alias"])
    assert train.kidney_alias.is_unique and dev.kidney_alias.is_unique
    assert set.union(*(set(cols) for cols in FEATURE_SETS.values())) <= set(train) & set(dev)
    report = {"image_routes_sha256": digest(ROUTER / "image_routes.csv"),
              "base_train_sha256": digest(BASE / "training_oof_predictions.csv"),
              "base_development_sha256": digest(BASE / "development_predictions.csv"),
              "base_condition": "Five base scores were generated by patient-OOF models on pooled training and fitted pooled-training models on development. Probe-specific heads fit only on the matching probe training OOF rows.",
              "selection": "Four feature sets, fixed balanced logistic C=0.1; four-fold patient-stratified meta OOF; maximize min(AUROC, AP), AUROC tie-break; development labels not used for selection.",
              "threshold": "Training meta-OOF maximum specificity with sensitivity >=0.85.",
              "test_APN_scored": False, "groups": {}}
    OUT.mkdir(parents=True, exist_ok=True)
    for probe in ("convex", "linear"):
        kidney_ids = set(routed.loc[routed.route.eq(probe), "kidney_alias"])
        tr = train[train.kidney_alias.isin(kidney_ids)].reset_index(drop=True)
        de = dev[dev.kidney_alias.isin(kidney_ids)].reset_index(drop=True)
        assert tr.patient_alias.nunique() >= 40 and de.patient_alias.nunique() >= 15
        assert set(tr.patient_alias).isdisjoint(de.patient_alias)
        state = people.set_index("patient_alias").DMSA_APN
        patient_train = tr.patient_alias.drop_duplicates().reset_index(drop=True)
        splits = list(StratifiedKFold(4, shuffle=True, random_state=SEED).split(
            patient_train, state.loc[patient_train]))
        oof_results = {}
        for name, columns in FEATURE_SETS.items():
            values = tr[columns].to_numpy(float)
            oof = np.full(len(tr), np.nan)
            for fit, hold in splits:
                fit_rows = np.flatnonzero(tr.patient_alias.isin(patient_train.iloc[fit]))
                hold_rows = np.flatnonzero(tr.patient_alias.isin(patient_train.iloc[hold]))
                oof[hold_rows] = head().fit(values[fit_rows], tr.label.iloc[fit_rows]).predict_proba(values[hold_rows])[:, 1]
            assert np.isfinite(oof).all()
            oof_results[name] = metric(tr.label, oof)
            oof_results[name]["scores"] = oof
        winner = max(FEATURE_SETS, key=lambda name: (
            min(oof_results[name]["auroc"], oof_results[name]["ap"]),
            oof_results[name]["auroc"],
        ))
        threshold, sensitivity = threshold_for_sensitivity(tr.label.to_numpy(int), oof_results[winner]["scores"])
        for item in oof_results.values():
            item.pop("scores")
        columns = FEATURE_SETS[winner]
        score = head().fit(tr[columns].to_numpy(float), tr.label).predict_proba(de[columns].to_numpy(float))[:, 1]
        labels = de.label.to_numpy(int)
        pred = score >= threshold
        result = {"train_patients": tr.patient_alias.nunique(), "train_kidneys": len(tr),
                  "development_patients": de.patient_alias.nunique(), "development_kidneys": len(de),
                  "positive_fraction": float(labels.mean()), "training_meta_oof": oof_results,
                  "selected_feature_set": winner, "selected_columns": columns,
                  "training_meta_oof_threshold": threshold, "training_meta_oof_sensitivity": sensitivity,
                  "development": metric(labels, score) | bootstrap(de.rename(columns={"label": "kidney_APN"}), score) | {
                      "sensitivity_at_training_threshold": float(pred[labels == 1].mean()),
                      "specificity_at_training_threshold": float((~pred[labels == 0]).mean()),
                  }}
        report["groups"][probe] = result
        de[["patient_alias", "kidney_alias", "side", "label"]].assign(
            probe_route=probe, selected_feature_set=winner, score=score,
            prediction=pred.astype(int)
        ).to_csv(OUT / f"{probe}_development_predictions.csv", index=False)
        print(probe, winner, result["development"], flush=True)
    (OUT / "probe_specific_meta_results.json").write_text(json.dumps(report, indent=2), encoding="utf-8")


if __name__ == "__main__":
    main()
